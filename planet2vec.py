# ======================= 1. LOAD =======================
def load(path, body=None, pixel_m=None, valid=None, name=""):
    """Wczytuje raster. Rozmiar piksela: z transformacji (układ rzutowany), z promienia ciała
    (układ geograficzny, podaj body='moon'/'mars'/'earth') albo ręcznie przez pixel_m.
    valid=(min, max): wartości poza zakresem -> NaN."""
    with rasterio.open(path) as src:
        arr = src.read(1).astype("float32")
        if src.nodata is not None:
            arr[arr == src.nodata] = np.nan
        crs, tf = src.crs, src.transform
    if valid is not None:
        arr[(arr < valid[0]) | (arr > valid[1])] = np.nan

    if pixel_m is None:
        if crs is not None and crs.is_projected:
            pixel_m = abs(tf.a)                     # zakładam metry (sprawdź jednostki układu!)
        elif body in BODY_RADIUS_M:
            pixel_m = abs(tf.a) * np.pi / 180 * BODY_RADIUS_M[body]
            print(f"UWAGA {name}: układ geograficzny, piksel liczony na równiku. "
                  "Na wysokich szerokościach E-W jest krótszy; lepiej przeprojektować.")
        else:
            raise ValueError("Podaj pixel_m albo body='moon'/'mars'/'earth'.")
    print(f"{name or path}: {arr.shape}, piksel {pixel_m:.1f} m, NaN {np.isnan(arr).mean():.1%}, "
          f"min/max {np.nanmin(arr):.1f}/{np.nanmax(arr):.1f}")
    return Raster(arr, float(pixel_m), name, tf, crs)


# ======================= 2. DOWNSAMPLE =======================
def downsample(r, target_m):
    """Zmniejsza rozdzielczość do target_m (uśrednianie z obsługą NaN, także dla ułamkowych
    współczynników). Nigdy nie zwiększa rozdzielczości. Zwraca nowy Raster ze FAKTYCZNYM pikselem.
    NaN (np. zamaskowane drzewa) nie są wypełniane ani nie zaniżają średnich przy brzegu maski."""
    f = target_m / r.pixel_m
    if f < 0.98:
        raise ValueError(f"{r.name}: target {target_m} m < obecne {r.pixel_m:.1f} m (upsampling zabroniony).")
    if f < 1.02:
        return r
    a = r.arr
    ok = np.isfinite(a)
    num = gaussian_filter(np.where(ok, a, 0).astype("float32"), f / 2, mode="nearest")
    den = gaussian_filter(ok.astype("float32"), f / 2, mode="nearest")
    valid = ok & (den > 0.5)                                            # oryginalne NaN zostają NaN
    sm = np.where(valid, num / np.maximum(den, 1e-6), 0.0).astype("float32")
    new = (round(a.shape[0] / f), round(a.shape[1] / f))
    zf = (new[0] / a.shape[0], new[1] / a.shape[1])
    zs = zoom(sm, zf, order=1, grid_mode=True, mode="nearest")
    zv = zoom(valid.astype("float32"), zf, order=1, grid_mode=True, mode="nearest")
    out = np.where(zv > 0.5, zs / np.maximum(zv, 1e-6), np.nan)         # normalizacja wagami -> bez biasu ku 0
    actual = r.pixel_m * a.shape[0] / new[0]
    tf = None
    if r.transform is not None:
        tf = r.transform * Affine.scale(a.shape[1] / out.shape[1], a.shape[0] / out.shape[0])
    print(f"{r.name}: {r.pixel_m:.1f} m -> {actual:.1f} m, {a.shape} -> {out.shape}")
    return Raster(out.astype("float32"), actual, r.name, tf, r.crs)


def plan_scale(native_m, n_px=64, request_extent_m=None, min_px=32):
    """Dobiera wspólną skalę dla Ziemi i celu.
    - rozdzielczość docelowa = najgrubsza z natywnych (nie wymyślamy szczegółów),
    - okno = n_px pikseli, więc po resamplingu ma ten sam rozmiar fizyczny po obu stronach,
    - jeśli obszar zapytania jest mniejszy niż okno, okno się zmniejsza (ale nie poniżej min_px).
    Zwraca (target_m, n_px, window_km)."""
    target = max(native_m)
    if request_extent_m is not None:
        fit = int(request_extent_m // target)
        if fit < n_px:
            n_px = max(fit, 0)
            if n_px < min_px:
                raise ValueError(f"Obszar zapytania mieści tylko {n_px} px przy {target:.0f} m/px "
                                 f"(min {min_px}). Za mały albo za gruby.")
            print(f"Okno zmniejszone do {n_px} px, bo zapytanie jest małe.")
    print(f"Skala: {target:.0f} m/px, okno {n_px} px = {n_px * target / 1000:.1f} km")
    return target, n_px, n_px * target / 1000


