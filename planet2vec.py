def _elev_bins(vals):
    mx = np.nanmax(vals)
    if np.allclose(vals, np.round(vals)):                           # dane całkowite -> biny całkowite
        bw = max(1, round(mx / 30))
        return np.arange(-0.5, mx + bw + 0.5, bw)
    return 30

def analysis(r, request=False, n_win=5, n=64, seed=9586, pos=None):
    """Podgląd rastra i okien. request=True -> jedno okno (domyślnie środek rastra, albo pos=(r,c)).
    Piksele zamaskowane (NaN) są jasnoszare."""
    dem, px = r.arr, r.pixel_m
    gx, gy, sl = _grad(dem, px)
    if request:
        n_win, pos_list = 1, [tuple(pos) if pos else _center(dem.shape, n)]
        p0 = pos_list[0]
        if np.isnan(dem[p0[0]:p0[0] + n, p0[1]:p0[1] + n]).mean() > MAX_NAN:
            raise ValueError(f"{r.name}: okno zapytania {p0} ma >{MAX_NAN:.0%} NaN - podaj inne pos=(wiersz, kol).")
    else:
        rng = np.random.default_rng(seed)       # losujemy tylko okna z dość dużą ilością ważnych pikseli
        pos_list, tries = [], 0
        while len(pos_list) < n_win:
            tries += 1
            if tries > 50_000:
                raise RuntimeError(f"{r.name}: za mało okien z >={1 - MAX_NAN:.0%} ważnych pikseli.")
            p = (int(rng.integers(0, dem.shape[0] - n + 1)), int(rng.integers(0, dem.shape[1] - n + 1)))
            if np.isnan(dem[p[0]:p[0] + n, p[1]:p[1] + n]).mean() <= MAX_NAN:
                pos_list.append(p)
    pk = px / 1000
    print(f"{r.name}: okno {n} px = {n * pk:.2f} km, raster {dem.shape[1] * pk:.0f} x {dem.shape[0] * pk:.0f} km")

    fig = plt.figure(figsize=(22, 2.6 * (n_win + 3.5)), constrained_layout=True)
    gs = fig.add_gridspec(n_win + 1, 5, height_ratios=[3.5] + [1] * n_win)
    ax0 = fig.add_subplot(gs[0, :])
    im = ax0.imshow(dem, cmap=_TERRAIN, extent=(0, dem.shape[1] * pk, dem.shape[0] * pk, 0))
    plt.colorbar(im, ax=ax0, shrink=0.8, label="wysokość [m]")
    for i, (rr, cc) in enumerate(pos_list):
        ax0.add_patch(Rectangle((cc * pk, rr * pk), n * pk, n * pk, fill=False, ec="red", lw=2))
        ax0.text(cc * pk, max(rr * pk - 0.3 * n * pk, 0), str(i + 1), color="red", fontsize=14, weight="bold")
    ax0.set_title(f"{r.name or 'DEM'} [km]" + ("  (ZAPYTANIE)" if request else ""))

    ext_w = (0, n * pk, n * pk, 0)
    bw = 180 / N_BINS
    centers = np.arange(N_BINS) * bw + bw / 2
    for i, (rr, cc) in enumerate(pos_list):
        sx = np.s_[rr:rr + n, cc:cc + n]
        d, s = dem[sx], sl[sx]
        rel = d - np.nanmin(d)
        rel_ok = rel[~np.isnan(rel)]
        s_ok = np.clip(s[~np.isnan(s)], 0, 31)
        h = _orient_hist(gx[sx], gy[sx])
        a = fig.add_subplot(gs[i + 1, 0]); m = a.imshow(rel, cmap=_TERRAIN, extent=ext_w)
        plt.colorbar(m, ax=a, label="m nad min.")
        a.set_title(f"Okno {i + 1}: wys. względna ({np.isfinite(d).mean():.0%} ważnych)")
        a = fig.add_subplot(gs[i + 1, 1])
        a.hist(rel_ok, bins=_elev_bins(rel_ok), weights=np.full(rel_ok.size, 1 / rel_ok.size), color="tab:green")
        a.set_title(f"Wys. względna (max {np.nanmax(rel):.0f} m)")
        a = fig.add_subplot(gs[i + 1, 2])
        a.hist(s_ok, bins=np.arange(0, 33, 2), weights=np.full(s_ok.size, 1 / s_ok.size), color="tab:red")
        a.set_title(f"Nachylenie (mediana {np.median(s_ok):.1f}°)")
        a = fig.add_subplot(gs[i + 1, 3]); a.bar(centers, h, width=bw * 0.9, color="tab:purple")
        a.set_title("Kierunki krawędzi (mod 180°)")
        a = fig.add_subplot(gs[i + 1, 4]); a.bar(np.arange(N_BINS), np.sort(h)[::-1], color="tab:orange")
        a.set_title(f"Posortowane (max {h.max():.2f})")
    plt.show()


# ======================= 4. TERRAIN2VEC =======================
def terrain2vec(r, n=64, request=False, scaler=None, stride=None, pos=None, store=None):
    """Liczy embeddingi okien.
    request=False: okna z całego rastra (siatka co stride, domyślnie n), skaler dopasowany do tych danych.
    request=True : JEDNO okno (środek lub pos), wymaga scaler=(mu, sd) z bazy (np. Ziemi).
    Zamaskowane piksele (NaN) są pomijane; okna z >MAX_NAN NaN odpadają.
    Wynik (Index) jest też dopisywany do listy store, jeśli ją podasz."""
    dem = r.arr
    if min(dem.shape) < n:
        raise ValueError(f"{r.name}: raster {dem.shape} mniejszy niż okno {n} px.")
    gx, gy, sl = _grad(dem, r.pixel_m)

    if request:
        if scaler is None:
            raise ValueError("request=True wymaga scaler=(mu, sd) z bazy Ziemi.")
        cand = [tuple(pos) if pos else _center(dem.shape, n)]
    else:
        st = stride or n
        cand = [(a, b) for a in range(0, dem.shape[0] - n + 1, st)
                       for b in range(0, dem.shape[1] - n + 1, st)]

    feats, kept = [], []
    for (a, b) in cand:
        sx = np.s_[a:a + n, b:b + n]
        if np.isnan(dem[sx]).mean() > MAX_NAN:
            continue
        feats.append(_window_features(dem[sx], sl[sx], gx[sx], gy[sx]))
        kept.append((a, b))
    if not feats:
        raise ValueError(f"{r.name}: brak okien spełniających MAX_NAN.")

    mu, sd = scaler if scaler is not None else _fit_scaler(feats)
    idx = Index(r.name, r.pixel_m, n, np.array(kept), feats, _embed(feats, mu, sd), mu, sd)
    print(f"{r.name}: okna {len(feats)}, wymiar {idx.E.shape[1]}")
    if store is not None:
        store.append(idx)
    return idx


