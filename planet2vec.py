def _target_dir(body):
    return ROOT / f"{body}_sites" / f"{body}_sites_elevation"

def _cache_dir(body):
    return ROOT / "earth" / f"prepared_{body}_bare"

def list_sites(body):
    """Nazwy dostępnych miejsc (pliki .tif) dla ciała."""
    d = _target_dir(body)
    return sorted(p.stem for p in d.glob("*.tif")) if d.is_dir() else []

def _write_json(path, data):
    tmp = str(path) + ".tmp"                      # zapis atomowy
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    os.replace(tmp, path)

def _entries_for_site(body, site, squares, first_id):
    """Wpisy sites.json dla jednego miejsca (wagi BLOCK_W stałe). Id rosną od first_id."""
    out, nid = [], first_id
    for s in squares:
        w = s.window
        if w.lat is None:
            print(f"UWAGA: {site} kwadrat {s.index} bez georeferencji - pominięty")
            continue
        for h in s.hits:
            if h.lat is None:
                print(f"UWAGA: {site} kwadrat {s.index} hit {h.rank} bez georeferencji - pominięty")
                continue
            chunk = h.raster.replace("Ziemia ", "").replace(" (bare)", "")
            out.append({
                "id": nid, "body": body, "source": site,
                "site": {"name": f"{site}, kwadrat {s.index}",
                         "lat": round(w.lat, 4), "lon": round(_lon180(w.lon), 4)},
                "earth": {"name": f"{chunk}, hit {h.rank}",
                          "lat": round(h.lat, 4), "lon": round(_lon180(h.lon), 4)},
                "side_km": round(w.side_m / 1000, 3),
            })
            nid += 1
    return out

def export_sites(path=SITES_JSON, bodies=None, k=5, samples=3, force=False):
    """Uzupełnia sites.json o miejsca, których tam jeszcze nie ma (wpis ma pole "source" = nazwa pliku .tif).
    Miejsca już obecne nie są ruszane. Wpisy bez "source" (ręczne) nigdy nie są zmieniane.
    force=True: kasuje wszystkie wpisy z "source" i liczy od nowa (po zmianie N_PX, BLOCK_W, danych Ziemi).
    Plik jest zapisywany po każdym miejscu, więc przerwanie nie traci postępu."""
    path = Path(path)
    data = []
    if path.exists():
        with open(path, encoding="utf-8") as f:
            txt = f.read().strip()
        data = json.loads(txt) if txt else []          # pusty plik = brak wpisów
    if force:
        data = [e for e in data if "source" not in e]
    done = {(e["body"], e["source"]) for e in data if "source" in e}

    for body in (bodies or sorted(BODY_PIXEL_M)):
        todo = [s for s in list_sites(body) if (body, s) not in done]
        if not todo:
            print(f"{body}: nic do policzenia")
            continue
        cache = _cache_dir(body)
        if not cache.is_dir():
            print(f"POMINIĘTO {body}: brak bazy Ziemi {cache} (uruchom prepare_earth_chunks)")
            continue
        for site in todo:
            try:
                db, q, order, dist, earth_ts, tgt_t, qs, results = find_analogs_multi(
                    str(cache), str(_target_dir(body) / f"{site}.tif"),
                    pixel_m=BODY_PIXEL_M[body], name=site, k=k, samples=samples, show=False)
                squares = collect_hits(db, qs, results, tgt_t)
            except Exception as e:
                print(f"POMINIĘTO {body}/{site}: {type(e).__name__}: {e}")
                continue
            first_id = max((e["id"] for e in data if e["body"] == body), default=0) + 1
            new = _entries_for_site(body, site, squares, first_id)
            if not new:
                print(f"POMINIĘTO {body}/{site}: brak wyników z georeferencją")
                continue
            data += new
            _write_json(path, data)
            print(f"{body}/{site}: dodano {len(new)} wpisów")
    print(f"sites.json: {len(data)} wpisów")
    return data


