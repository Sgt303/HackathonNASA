def _lon180(x):
    return (x + 180) % 360 - 180            # długość do zakresu -180..180

def chunk_centers(rasters):
    """Środek i wielkość każdego chunka (własny pas UTM każdego).
    rasters: earth_ts z find_analogs_multi albo load_earth_chunks(CACHE).
    Zwraca listę słowników: name, lat, lon, crs, rows, cols, height_km, width_km, area_km2."""
    out = []
    for r in rasters:
        h, w = r.arr.shape
        lat = lon = None
        if r.transform is not None and r.crs is not None:
            x, y = r.transform * (w / 2, h / 2)
            lon, lat = _transformer(r.crs).transform(x, y)
            lat, lon = float(lat), float(lon)
        hk, wk = h * r.pixel_m / 1000, w * r.pixel_m / 1000
        out.append({"name": r.name, "lat": lat, "lon": lon, "crs": _crs_name(r.crs),
                    "rows": h, "cols": w, "pixel_m": r.pixel_m,
                    "height_km": hk, "width_km": wk, "area_km2": hk * wk})
    return out


