def _sample_positions(dem, n, center, samples, radius, seed, min_sep):
    """Środkowe okno + `samples` losowych okien w promieniu `radius` px od niego.
    Odrzuca okna poza rastrem, z >MAX_NAN NaN i bliższe niż min_sep px (Czebyszew) od już wybranych."""
    rng = np.random.default_rng(seed)
    c = tuple(center) if center else _center(dem.shape, n)
    chosen, tries = [c], 0
    while len(chosen) < samples + 1:
        tries += 1
        if tries > 5000:
            print(f"UWAGA: wylosowano tylko {len(chosen) - 1}/{samples} dodatkowych okien "
                  "(zwiększ radius_px lub zmniejsz min_sep)")
            break
        a = c[0] + int(rng.integers(-radius, radius + 1))
        b = c[1] + int(rng.integers(-radius, radius + 1))
        if a < 0 or b < 0 or a + n > dem.shape[0] or b + n > dem.shape[1]:
            continue
        if np.isnan(dem[a:a + n, b:b + n]).mean() > MAX_NAN:
            continue
        if any(max(abs(a - x), abs(b - y)) < min_sep for x, y in chosen):
            continue
        chosen.append((a, b))
    return chosen


