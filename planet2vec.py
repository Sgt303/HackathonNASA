def _tile_name(lat, lon):       # kafle WorldCover 3x3°, nazwa = lewy dolny róg
    return f"{'N' if lat >= 0 else 'S'}{abs(lat):02d}{'E' if lon >= 0 else 'W'}{abs(lon):03d}"

def _masks_from_wc(wc, arr, up, bare_frac=0.5, tree_frac=0.5, erode_px=1, bare_classes=(WC_BARE,)):
    """wc: raster klas 10 m (up x gęstszy niż arr). Zwraca Landcover na siatce arr."""
    H, W = arr.shape
    frac = lambda m: m.reshape(H, up, W, up).sum(axis=(1, 3), dtype="uint16") / up**2
    bare = frac(np.isin(wc, bare_classes)) >= bare_frac - 1e-9
    if erode_px > 0:     # zdejmij piksele przy granicy (gradient przy krawędzi lasu łapie wysokość koron)
        bare = binary_erosion(bare, iterations=erode_px, border_value=1)
    bare &= np.isfinite(arr)
    tree = frac(wc == WC_TREE) >= tree_frac - 1e-9
    veg = frac(np.isin(wc, WC_VEG)) >= tree_frac - 1e-9
    cls, cnt = np.unique(wc, return_counts=True)
    return Landcover(tree, veg, bare, dict(zip(cls.tolist(), cnt.tolist())))

def landcover_masks(r, bare_frac=0.5, tree_frac=0.5, erode_px=1, bare_classes=(WC_BARE,)):
    """Pobiera ESA WorldCover (10 m) dla obszaru rastra Ziemi i zwraca maski na jego siatce.
    bare_classes: klasy WorldCover liczone jako teren do bazy (domyślnie tylko 60; (60, 20) dodaje krzewy).
    Raster musi mieć transform i układ rzutowany w metrach (load go zapisuje) oraz piksel będący
    wielokrotnością 10 m. Wywołuj na rastrze W NATYWNEJ rozdzielczości (przed downsample)."""
    if r.transform is None or r.crs is None:
        raise ValueError("Raster bez transform/crs - wczytaj go przez load().")
    if not r.crs.is_projected:
        raise ValueError("Układ geograficzny (stopnie) - przeprojektuj raster na układ w metrach.")
    H, W = r.arr.shape
    tf = r.transform
    px = abs(tf.a)
    up = round(px / 10)
    if up < 1 or abs(up * 10 - px) > 1e-6:
        raise ValueError(f"Piksel {px:.2f} m nie jest wielokrotnością 10 m.")

    left, top = tf.c, tf.f
    right, bottom = left + W * tf.a, top + H * tf.e
    west, south, east, north = transform_bounds(r.crs, "EPSG:4326", left, bottom, right, top)
    tiles = [(la, lo) for la in range(floor(south / 3) * 3, floor(north / 3) * 3 + 1, 3)
                      for lo in range(floor(west / 3) * 3, floor(east / 3) * 3 + 1, 3)]
    print("Kafle WorldCover:", [_tile_name(*t) for t in tiles])

    wc_tf = tf * Affine.scale(1 / up)
    wc = np.zeros((H * up, W * up), dtype="uint8")
    loaded = 0
    for la, lo in tiles:
        try:
            with rasterio.open(WC_URL.format(tile=_tile_name(la, lo))) as src:
                reproject(source=rasterio.band(src, 1), destination=wc, dst_transform=wc_tf, dst_crs=r.crs,
                          src_nodata=0, dst_nodata=0, init_dest_nodata=False, resampling=Resampling.nearest)
            loaded += 1
        except rasterio.errors.RasterioIOError as e:
            print("Brak/nie udało się wczytać kafla", _tile_name(la, lo), "->", e)
    if loaded == 0:
        raise RuntimeError("WorldCover: żaden kafel się nie wczytał (sprawdź URL/internet).")

    lc = _masks_from_wc(wc, r.arr, up, bare_frac, tree_frac, erode_px, bare_classes)
    print(f"{r.name}: drzewa {lc.tree.mean():.1%} | cała roślinność {lc.veg.mean():.1%} | bare {lc.bare.mean():.1%}")
    print("Klasy:", {WC_NAMES.get(k, k): v for k, v in lc.counts.items()})
    return lc

