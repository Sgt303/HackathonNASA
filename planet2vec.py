def find_analogs(earth_bare, target_path, body=None, pixel_m=None, name="Cel",
                 n_px=N_PX, k=5, pos=None, show=True, samples=0, radius_px=None,
                 min_sep=None, seed=0):
    """Pełny przebieg: wczytaj cel (Księżyc/Mars), dobierz skalę, przeskaluj Ziemię i cel,
    policz bazę Ziemi i zapytania, wyszukaj top-k, pokaż wyniki.
    earth_bare: Raster Ziemi po apply_mask (w natywnej rozdzielczości).
    samples=n: oprócz oryginalnego okna losuje n dodatkowych okien w promieniu radius_px
      (domyślnie 2*n_px) i szuka dla każdego osobno; 0 = tylko oryginał.
    min_sep: minimalny odstęp okien zapytań w px (domyślnie n//2; n = bez nakładania).
    Zwraca (db, q, order, dist, earth_t, tgt_t, qs, results); q/order/dist dotyczą oryginału,
    qs/results to listy dla wszystkich sampli (indeks 0 = oryginał)."""
    tgt = load(target_path, body=body, pixel_m=pixel_m, name=name)
    extent = min(tgt.arr.shape) * tgt.pixel_m
    target_m, n, km = plan_scale([earth_bare.pixel_m, tgt.pixel_m], n_px=n_px, request_extent_m=extent)
    if n != n_px:
        raise ValueError(f"{name}: cel mieści tylko okno {n} px, wymagane {n_px} px "
                         f"({n_px * target_m / 1000:.2f} km). Cel za mały dla tej skali.")

    earth_t = downsample(earth_bare, target_m)
    tgt_t = downsample(tgt, target_m)

    if show:
        #analysis(earth_t, n=n)
        analysis(tgt_t, request=True, n=n, pos=pos)

    db = terrain2vec(earth_t, n=n, stride=n // 2)

    plist = _sample_positions(tgt_t.arr, n, pos, samples, radius_px or 2 * n, seed, min_sep or n // 2)
    qs, results = [], []
    for p in plist:
        q_i = terrain2vec(tgt_t, n=n, request=True, scaler=(db.mu, db.sd), pos=p)
        qs.append(q_i)
        results.append(search(q_i, db, k=k))

    q, (order, dist) = qs[0], results[0]
    d_all = np.linalg.norm(db.E - q.E[0], axis=1)
    print("rozkład odległości (min, 5%, 50%, 95%):", np.round(np.percentile(d_all, [0, 5, 50, 95]), 2))
    if show:
        show_matches(tgt_t, q, earth_t, db, order, dist)      # szczegóły dla oryginału
        if samples > 0:
            show_samples(tgt_t, qs, earth_t, db, results)
    return db, q, order, dist, earth_t, tgt_t, qs, results


# ======================= BAZA Z WIELU RASTRÓW (np. kilka kawałków Ziemi) =======================
def _collect(r, n, stride):
    """Cechy wszystkich okien jednego rastra (bez normalizacji)."""
    dem = r.arr
    if min(dem.shape) < n:
        return [], []
    gx, gy, sl = _grad(dem, r.pixel_m)
    feats, kept = [], []
    for a in range(0, dem.shape[0] - n + 1, stride):
        for b in range(0, dem.shape[1] - n + 1, stride):
            sx = np.s_[a:a + n, b:b + n]
            if np.isnan(dem[sx]).mean() > MAX_NAN:
                continue
            feats.append(_window_features(dem[sx], sl[sx], gx[sx], gy[sx]))
            kept.append((a, b))
    return feats, kept

def terrain2vec_multi(rasters, n=64, stride=None):
    """Jedna baza z wielu rastrów o tej samej skali. Wspólny skaler (mu, sd) dla WSZYSTKICH okien,
    więc embeddingi z różnych rastrów są porównywalne. Index.src mówi, z którego rastra jest okno."""
    px = rasters[0].pixel_m
    if any(abs(r.pixel_m - px) / px > 0.02 for r in rasters):
        raise ValueError("Rastry mają różne rozmiary piksela - przeskaluj je do tego samego target_m.")
    st = stride or n
    all_feats, all_pos, all_src = [], [], []
    for j, r in enumerate(rasters):
        f, p = _collect(r, n, st)
        print(f"{r.name}: okna {len(f)}")
        all_feats += f; all_pos += p; all_src += [j] * len(f)
    if not all_feats:
        raise ValueError("Żaden raster nie ma okien spełniających MAX_NAN.")
    mu, sd = _fit_scaler(all_feats)
    idx = Index("baza", px, n, np.array(all_pos), all_feats, _embed(all_feats, mu, sd), mu, sd,
                src=np.array(all_src), rasters=list(rasters))
    print(f"baza: {len(all_feats)} okien z {len(rasters)} rastrów, wymiar {idx.E.shape[1]}")
    return idx

