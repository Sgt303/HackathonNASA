# ======================= CECHY (wspólne) =======================
def _grad(dem, px):
    gy, gx = np.gradient(dem, px)
    return gx, gy, np.degrees(np.arctan(np.hypot(gx, gy)))

def _orient_hist(gx, gy, n_bins=N_BINS):
    mag = np.hypot(gx, gy)
    ok = np.isfinite(mag)
    ang = (np.degrees(np.arctan2(gy[ok], gx[ok])) + 90) % 180      # styczna, mod 180°
    h, _ = np.histogram(ang, bins=n_bins, range=(0, 180), weights=mag[ok])
    return h / h.sum() if h.sum() > 0 else h

def _window_features(d, s, gx, gy):
    rel = d - np.nanmin(d)
    p5, p95 = np.nanpercentile(rel, [5, 95])
    rg = p95 - p5
    return {
        "elev_scale": np.array([np.log1p(rg)]),
        "elev_shape": (np.nanpercentile(rel, Q_SHAPE) - p5) / max(rg, 1e-3),
        "slope": np.nanpercentile(s, Q_SLOPE),
        "orient": np.sort(_orient_hist(gx, gy))[::-1],
    }

def _center(shape, n):
    return ((shape[0] - n) // 2, (shape[1] - n) // 2)

def _fit_scaler(feats):
    mu, sd = {}, {}
    for b in BLOCK_W:
        X = np.array([f[b] for f in feats])
        mu[b] = np.nanmean(X, axis=0)
        s = np.nanstd(X, axis=0)
        sd[b] = np.where(s > 1e-9, s, 1.0)
    return mu, sd

def _embed(feats, mu, sd):
    parts = []
    for b, w in BLOCK_W.items():
        X = (np.array([f[b] for f in feats]) - mu[b]) / sd[b]
        parts.append(w * X / np.sqrt(X.shape[1]))
    return np.hstack(parts)


