def _draw_rect_maps(fig, subspec, rasters, rects, n, title):
    """Mapy rastrów z zaznaczonymi oknami. rects: (nr_rastra, wiersz, kol, kolor, tekst, rozmiar_tekstu, lw, tekst_w_oknie).
    Rysuje po jednej mapie dla każdego rastra, w którym jest choć jedno okno. Zwraca listę osi."""
    used = sorted({r[0] for r in rects})
    inner = subspec.subgridspec(1, len(used))
    axes = []
    for col, k in enumerate(used):
        r = rasters[k]
        pk = r.pixel_m / 1000
        a = fig.add_subplot(inner[0, col])
        im = a.imshow(r.arr, cmap=_TERRAIN, extent=(0, r.arr.shape[1] * pk, r.arr.shape[0] * pk, 0))
        plt.colorbar(im, ax=a, shrink=0.8, label="wysokość [m]")
        for kk, rr, cc, color, txt, fs, lw, inside in rects:
            if kk != k:
                continue
            a.add_patch(Rectangle((cc * pk, rr * pk), n * pk, n * pk, fill=False, ec=color, lw=lw))
            if txt and inside:
                a.text(cc * pk + 0.05, rr * pk + n * pk * 0.95, txt, color=color, fontsize=fs)
            elif txt:
                a.text(cc * pk, max(rr * pk - 0.3 * n * pk, 0), txt, color=color, fontsize=fs, weight="bold")
        a.set_title(f"{r.name} [km]{title}")
        axes.append(a)
    return axes


