def _save_raster(r, path):
    tmp = path + ".tmp.npz"                       # zapis atomowy
    np.savez_compressed(
        tmp, arr=r.arr, pixel_m=r.pixel_m, name=r.name,
        transform=np.array(tuple(r.transform)[:6]) if r.transform is not None else np.array([]),
        crs=r.crs.to_wkt() if r.crs is not None else "")
    os.replace(tmp, path)

def _load_raster(path):
    z = np.load(path, allow_pickle=False)
    tf = Affine(*z["transform"]) if z["transform"].size == 6 else None
    wkt = str(z["crs"])
    return Raster(z["arr"], float(z["pixel_m"]), str(z["name"]), tf, CRS.from_wkt(wkt) if wkt else None)

def prepare_earth_chunks(chunk_paths, out_dir, target_m=40, earth_px=30, use_mask=True,
                         bare_frac=0.5, bare_classes=(WC_BARE,), show=False, overwrite=False):
    """Uruchom RAZ. Dla każdego kawałka: wczytaj -> maska WorldCover (opcjonalnie) -> downsample do target_m
    -> zapisz do out_dir. Potem find_analogs_multi(out_dir, ...) tylko je czyta.
    target_m: skala bazy. Cel (Księżyc) musi mieć piksel <= target_m (inaczej trzeba przygotować bazę grubszą)."""
    os.makedirs(out_dir, exist_ok=True)
    meta = dict(target_m=target_m, earth_px=earth_px, use_mask=use_mask, bare_frac=bare_frac,
                bare_classes=list(bare_classes), chunks=[os.path.basename(p) for p in chunk_paths])
    mp = os.path.join(out_dir, "meta.json")
    if os.path.exists(mp) and not overwrite:
        old = json.load(open(mp))
        if old != meta:
            raise ValueError(f"{out_dir} zawiera bazę z innymi parametrami:\n  {old}\nnowe:\n  {meta}\n"
                             "Użyj overwrite=True albo innego folderu.")
    for p in chunk_paths:
        base = os.path.splitext(os.path.basename(p))[0]
        outp = os.path.join(out_dir, base + ".npz")
        if os.path.exists(outp) and not overwrite:
            print(f"{base}: już jest, pomijam")
            continue
        r = load(p, pixel_m=earth_px, name="Ziemia " + base)
        if use_mask:
            lc = landcover_masks(r, bare_frac=bare_frac, bare_classes=bare_classes)
            if show:
                show_masks(r, lc)
            r = apply_mask(r, lc.bare)
            del lc
        r = downsample(r, target_m)
        _save_raster(r, outp)
        print(f"  zapisano {outp}")
        del r
    json.dump(meta, open(mp, "w"), indent=1)
    print("gotowe:", out_dir)

def load_earth_chunks(cache_dir):
    files = sorted(f for f in glob.glob(os.path.join(cache_dir, "*.npz")) if not f.endswith(".tmp.npz"))
    if not files:
        raise FileNotFoundError(f"Brak plików .npz w {cache_dir}. Najpierw uruchom prepare_earth_chunks.")
    return [_load_raster(f) for f in files]


